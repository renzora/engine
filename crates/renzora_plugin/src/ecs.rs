impl Vec3 {
    pub const ZERO: Vec3 = Vec3 { x: 0.0, y: 0.0, z: 0.0 };
    pub const ONE: Vec3 = Vec3 { x: 1.0, y: 1.0, z: 1.0 };
    pub const X: Vec3 = Vec3 { x: 1.0, y: 0.0, z: 0.0 };
    pub const Y: Vec3 = Vec3 { x: 0.0, y: 1.0, z: 0.0 };
    pub const Z: Vec3 = Vec3 { x: 0.0, y: 0.0, z: 1.0 };

    pub const fn new(x: f32, y: f32, z: f32) -> Vec3 {
        Vec3 { x, y, z }
    }
    pub const fn splat(v: f32) -> Vec3 {
        Vec3 { x: v, y: v, z: v }
    }
    pub fn dot(self, o: Vec3) -> f32 {
        self.x * o.x + self.y * o.y + self.z * o.z
    }
    pub fn cross(self, o: Vec3) -> Vec3 {
        Vec3::new(
            self.y * o.z - self.z * o.y,
            self.z * o.x - self.x * o.z,
            self.x * o.y - self.y * o.x,
        )
    }
    pub fn length(self) -> f32 {
        self.dot(self).sqrt()
    }
    pub fn length_squared(self) -> f32 {
        self.dot(self)
    }
    pub fn distance(self, o: Vec3) -> f32 {
        (self - o).length()
    }
    /// Returns `ZERO` for a zero-length vector rather than `NaN` — a normalise
    /// in a loop over positions will hit coincident points sooner or later, and
    /// a silent NaN poisons everything downstream.
    pub fn normalize_or_zero(self) -> Vec3 {
        let len = self.length();
        if len > 1e-6 {
            self / len
        } else {
            Vec3::ZERO
        }
    }
    pub fn normalize(self) -> Vec3 {
        self / self.length()
    }
    pub fn lerp(self, o: Vec3, t: f32) -> Vec3 {
        self + (o - self) * t
    }
    pub fn clamp_length_max(self, max: f32) -> Vec3 {
        let len = self.length();
        if len > max && len > 1e-6 {
            self * (max / len)
        } else {
            self
        }
    }
}

