impl Quat {
    pub const IDENTITY: Quat = Quat { x: 0.0, y: 0.0, z: 0.0, w: 1.0 };

    pub fn from_axis_angle(axis: Vec3, angle: f32) -> Quat {
        let (s, c) = (angle * 0.5).sin_cos();
        let a = axis.normalize_or_zero();
        Quat { x: a.x * s, y: a.y * s, z: a.z * s, w: c }
    }
    pub fn from_rotation_x(angle: f32) -> Quat {
        let (s, c) = (angle * 0.5).sin_cos();
        Quat { x: s, y: 0.0, z: 0.0, w: c }
    }
    pub fn from_rotation_y(angle: f32) -> Quat {
        let (s, c) = (angle * 0.5).sin_cos();
        Quat { x: 0.0, y: s, z: 0.0, w: c }
    }
    pub fn from_rotation_z(angle: f32) -> Quat {
        let (s, c) = (angle * 0.5).sin_cos();
        Quat { x: 0.0, y: 0.0, z: s, w: c }
    }
}

impl core::ops::Mul for Quat {
    type Output = Quat;
    fn mul(self, r: Quat) -> Quat {
        Quat {
            x: self.w * r.x + self.x * r.w + self.y * r.z - self.z * r.y,
            y: self.w * r.y - self.x * r.z + self.y * r.w + self.z * r.x,
            z: self.w * r.z + self.x * r.y - self.y * r.x + self.z * r.w,
            w: self.w * r.w - self.x * r.x - self.y * r.y - self.z * r.z,
        }
    }
}

impl core::ops::Mul<Vec3> for Quat {
    type Output = Vec3;
    /// Rotate a vector. `v + 2w(q x v) + 2(q x (q x v))`.
    fn mul(self, v: Vec3) -> Vec3 {
        let q = Vec3::new(self.x, self.y, self.z);
        let t = q.cross(v) * 2.0;
        v + t * self.w + q.cross(t)
    }
}

impl Default for Quat {
    fn default() -> Self {
        Quat::IDENTITY
    }
}

impl Transform {
    pub const IDENTITY: Transform = Transform {
        translation: Vec3::ZERO,
        rotation: Quat::IDENTITY,
        scale: Vec3::ONE,
    };

    pub const fn from_xyz(x: f32, y: f32, z: f32) -> Transform {
        Transform {
            translation: Vec3::new(x, y, z),
            rotation: Quat::IDENTITY,
            scale: Vec3::ONE,
        }
    }
    pub const fn from_translation(translation: Vec3) -> Transform {
        Transform {
            translation,
            rotation: Quat::IDENTITY,
            scale: Vec3::ONE,
        }
    }
    pub const fn with_scale(mut self, scale: Vec3) -> Transform {
        self.scale = scale;
        self
    }
    pub const fn with_translation(mut self, translation: Vec3) -> Transform {
        self.translation = translation;
        self
    }

    pub fn rotate(&mut self, q: Quat) {
        self.rotation = q * self.rotation;
    }
    pub fn rotate_x(&mut self, angle: f32) {
        self.rotation = self.rotation * Quat::from_rotation_x(angle);
    }
    pub fn rotate_y(&mut self, angle: f32) {
        self.rotation = self.rotation * Quat::from_rotation_y(angle);
    }
    pub fn rotate_z(&mut self, angle: f32) {
        self.rotation = self.rotation * Quat::from_rotation_z(angle);
    }

    pub fn forward(&self) -> Vec3 {
        self.rotation * -Vec3::Z
    }
    pub fn back(&self) -> Vec3 {
        self.rotation * Vec3::Z
    }
    pub fn right(&self) -> Vec3 {
        self.rotation * Vec3::X
    }
    pub fn left(&self) -> Vec3 {
        self.rotation * -Vec3::X
    }
    pub fn up(&self) -> Vec3 {
        self.rotation * Vec3::Y
    }
    pub fn down(&self) -> Vec3 {
        self.rotation * -Vec3::Y
    }
}

impl Default for Transform {
    fn default() -> Self {
        Transform::IDENTITY
    }
}

// ── Init context ─────────────────────────────────────────────────────────────

/// Resolves component ids during `Plugin::build`, caching so a type is
/// registered or looked up once regardless of how many systems name it.
pub struct InitCtx {
    iface: *const sys::Interface,
    host: *mut sys::Host,
    cache: alloc::vec::Vec<(&'static str, sys::ComponentId)>,
    /// Type path of the first component that failed to resolve, if any.
    ///
    /// A plugin naming a component the host does not expose must refuse to load.
    /// Carrying on would register a system whose query can never match, which
    /// presents as "my plugin loaded but does nothing" — far harder to diagnose
    /// than a refusal at startup.
    unresolved: Option<&'static str>,
}

impl InitCtx {
    /// Register `T` as a resource and cache the id on the type.
    ///
    /// Registration is idempotent host-side (a second call returns the same id
    /// and leaves the existing value alone), so two systems both taking
    /// `ResMut<Score>` do not reset it between them.
    fn resource_id_of<T: Resource>(&mut self) -> sys::ComponentId {
        // Cached on the `InitCtx`, not on the type. The type's cell is the
        // *runtime* lookup key and is only correct for the world this plugin was
        // loaded into; short-circuiting on it would let one world's id leak into
        // another and silently skip registration there.
        if let Some((_, id)) = self.cache.iter().find(|(p, _)| *p == T::TYPE_PATH) {
            return *id;
        }
        let desc = T::descriptor();
        // SAFETY: `iface`/`host` are valid for the whole init call.
        let id = unsafe { ((*self.iface).register_resource)(self.host, &desc) };
        if !id.is_valid() && self.unresolved.is_none() {
            self.unresolved = Some(T::TYPE_PATH);
        }
        T::id_cell().store(id.0, core::sync::atomic::Ordering::Relaxed);
        self.cache.push((T::TYPE_PATH, id));
        id
    }

    fn id_of<T: Component>(&mut self) -> sys::ComponentId {
        if let Some((_, id)) = self.cache.iter().find(|(p, _)| *p == T::TYPE_PATH) {
            return *id;
        }
        // SAFETY: `iface`/`host` are valid for the whole init call.
        let id = unsafe {
            match T::descriptor() {
                Some(desc) => ((*self.iface).register_component)(self.host, &desc),
                None => ((*self.iface).component_id_by_name)(
                    self.host,
                    sys::StrRef::new(T::TYPE_PATH),
                ),
            }
        };
        if !id.is_valid() && self.unresolved.is_none() {
            self.unresolved = Some(T::TYPE_PATH);
        }
        // Cache on the type itself, so systems can reach it later.
        T::id_cell().store(id.0, core::sync::atomic::Ordering::Relaxed);
        self.cache.push((T::TYPE_PATH, id));
        id
    }
}

/// The id the host assigned `T`, or `INVALID` if it was never registered.
///
/// Registration happens during `Plugin::build`; a system naming a component the
/// plugin never registered gets `INVALID`, and the host ignores commands
/// carrying it rather than guessing.
pub fn component_id_of<T: Component>() -> sys::ComponentId {
    sys::ComponentId(T::id_cell().load(core::sync::atomic::Ordering::Relaxed))
}

// ── Query data ───────────────────────────────────────────────────────────────

/// What a query reads or writes. Implemented for `&T`, `&mut T`, and tuples.
///
/// # Safety
/// `CELLS` must equal the number of terms `terms` pushes, and `fetch` must read
/// exactly that many cells. The host lays cells out row-major on that promise.
pub unsafe trait QueryData {
    type Item<'a>;
    /// Cells this contributes per row. Zero for terms that read something other
    /// than component data, like [`Entity`].
    const CELLS: usize;
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>);
    /// # Safety
    /// `cells` points at this item's first cell in the row `row`, and `view` is
    /// live. `'a` is unbounded: the item borrows the host's staging buffers,
    /// which outlive the call but are not reachable from any argument, so
    /// nothing in the types can express the real bound. The caller is
    /// responsible for not letting an item escape the system body.
    unsafe fn fetch<'a>(
        view: *const sys::QueryView,
        row: usize,
        cells: *mut *mut u8,
    ) -> Self::Item<'a>;
}

/// Yields the entity being iterated. Mirrors Bevy's `Entity` query term.
///
/// Contributes no cell and no term — the host already sends an entity id per
/// row alongside the component data, so this costs nothing beyond reading it.
/// Without it a system cannot act on the entity it is looking at, which makes
/// "do this once, then mark it done" unwritable.
unsafe impl QueryData for sys::Entity {
    type Item<'a> = sys::Entity;
    const CELLS: usize = 0;
    fn terms(_: &mut InitCtx, _: &mut alloc::vec::Vec<sys::Term>) {}
    unsafe fn fetch<'a>(
        view: *const sys::QueryView,
        row: usize,
        _cells: *mut *mut u8,
    ) -> Self::Item<'a> {
        if (*view).entities.is_null() {
            return sys::Entity(u64::MAX);
        }
        *(*view).entities.add(row)
    }
}

unsafe impl<T: Component> QueryData for &T {
    type Item<'a> = &'a T;
    const CELLS: usize = 1;
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        out.push(sys::Term { component: ctx.id_of::<T>(), access: sys::Access::Read });
    }
    unsafe fn fetch<'a>(_: *const sys::QueryView, _: usize, cells: *mut *mut u8) -> &'a T {
        &*(*cells as *const T)
    }
}

unsafe impl<T: Component> QueryData for &mut T {
    type Item<'a> = &'a mut T;
    const CELLS: usize = 1;
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        out.push(sys::Term { component: ctx.id_of::<T>(), access: sys::Access::Write });
    }
    unsafe fn fetch<'a>(_: *const sys::QueryView, _: usize, cells: *mut *mut u8) -> &'a mut T {
        &mut *(*cells as *mut T)
    }
}

/// Reads `T` when the entity has it. Mirrors Bevy's `Option<&T>`.
///
/// The term does not filter, so the entity matches either way and the cell is
/// null when the component is absent — which is what makes "every entity, plus
/// this extra data if it happens to be there" a single query instead of two.
unsafe impl<T: Component> QueryData for Option<&T> {
    type Item<'a> = Option<&'a T>;
    const CELLS: usize = 1;
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        out.push(sys::Term { component: ctx.id_of::<T>(), access: sys::Access::ReadOptional });
    }
    unsafe fn fetch<'a>(_: *const sys::QueryView, _: usize, cells: *mut *mut u8) -> Option<&'a T> {
        (*cells).cast::<T>().as_ref()
    }
}

unsafe impl<T: Component> QueryData for Option<&mut T> {
    type Item<'a> = Option<&'a mut T>;
    const CELLS: usize = 1;
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        out.push(sys::Term { component: ctx.id_of::<T>(), access: sys::Access::WriteOptional });
    }
    unsafe fn fetch<'a>(
        _: *const sys::QueryView,
        _: usize,
        cells: *mut *mut u8,
    ) -> Option<&'a mut T> {
        (*cells).cast::<T>().as_mut()
    }
}

unsafe impl<A: QueryData, B: QueryData, C: QueryData> QueryData for (A, B, C) {
    type Item<'a> = (A::Item<'a>, B::Item<'a>, C::Item<'a>);
    const CELLS: usize = A::CELLS + B::CELLS + C::CELLS;
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        A::terms(ctx, out);
        B::terms(ctx, out);
        C::terms(ctx, out);
    }
    unsafe fn fetch<'a>(
        view: *const sys::QueryView,
        row: usize,
        cells: *mut *mut u8,
    ) -> Self::Item<'a> {
        (
            A::fetch(view, row, cells),
            B::fetch(view, row, cells.add(A::CELLS)),
            C::fetch(view, row, cells.add(A::CELLS + B::CELLS)),
        )
    }
}

unsafe impl<A: QueryData, B: QueryData> QueryData for (A, B) {
    type Item<'a> = (A::Item<'a>, B::Item<'a>);
    const CELLS: usize = A::CELLS + B::CELLS;
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        A::terms(ctx, out);
        B::terms(ctx, out);
    }
    unsafe fn fetch<'a>(
        view: *const sys::QueryView,
        row: usize,
        cells: *mut *mut u8,
    ) -> Self::Item<'a> {
        (
            A::fetch(view, row, cells),
            B::fetch(view, row, cells.add(A::CELLS)),
        )
    }
}

// ── Query filters ────────────────────────────────────────────────────────────

/// Filter terms. Contribute no cells — see [`sys::Access::With`].
pub trait QueryFilter {
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>);
}

impl QueryFilter for () {
    fn terms(_: &mut InitCtx, _: &mut alloc::vec::Vec<sys::Term>) {}
}

/// Matches entities that have `T`.
pub struct With<T>(PhantomData<T>);

impl<T: Component> QueryFilter for With<T> {
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        out.push(sys::Term { component: ctx.id_of::<T>(), access: sys::Access::With });
    }
}

/// Matches entities that do not have `T`.
pub struct Without<T>(PhantomData<T>);

impl<T: Component> QueryFilter for Without<T> {
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        out.push(sys::Term { component: ctx.id_of::<T>(), access: sys::Access::Without });
    }
}

impl<A: QueryFilter, B: QueryFilter> QueryFilter for (A, B) {
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        A::terms(ctx, out);
        B::terms(ctx, out);
    }
}

impl<A: QueryFilter, B: QueryFilter, C: QueryFilter> QueryFilter for (A, B, C) {
    fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
        A::terms(ctx, out);
        B::terms(ctx, out);
        C::terms(ctx, out);
    }
}

/// Matches entities satisfying any branch. Mirrors `bevy::Or<(..)>`.
///
/// Encoded as a bracketed run of terms — [`sys::Access::OrBegin`], one branch
/// per [`sys::Access::OrNext`] separator, then [`sys::Access::OrEnd`] — rather
/// than as a nested descriptor, so a query stays one flat term list at the
/// boundary no matter how the filter is spelled.
pub struct Or<T>(PhantomData<T>);

macro_rules! or_filters {
    ($(($first:ident $(, $rest:ident)*))+) => {
        $(
            impl<$first: QueryFilter $(, $rest: QueryFilter)*> QueryFilter
                for Or<($first, $($rest,)*)>
            {
                fn terms(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>) {
                    out.push(sys::Term::marker(sys::Access::OrBegin));
                    $first::terms(ctx, out);
                    $(
                        out.push(sys::Term::marker(sys::Access::OrNext));
                        $rest::terms(ctx, out);
                    )*
                    out.push(sys::Term::marker(sys::Access::OrEnd));
                }
            }
        )+
    };
}

or_filters! {
    (A, B)
    (A, B, C)
    (A, B, C, D)
}

// ── Query ────────────────────────────────────────────────────────────────────

/// A view over the entities this system matched. Mirrors `bevy_ecs::Query`.
pub struct Query<'a, D: QueryData, F: QueryFilter = ()> {
    view: sys::QueryView,
    _p: PhantomData<(&'a (), D, F)>,
}

impl<'a, D: QueryData, F: QueryFilter> Query<'a, D, F> {
    /// # Safety
    /// `view` must index a live [`sys::QueryView`] whose terms were declared by
    /// this exact `D`/`F` pair.
    unsafe fn new(call: *const sys::SystemCall, view: usize) -> Self {
        // Copied, not borrowed. A `QueryView` is four words and `Copy`, so this
        // is free — and it keeps the whole lifetime and `Sync` question out of
        // the type, which a `&'static` fallback for the out-of-range case would
        // otherwise drag in.
        let view = if view < (*call).view_count {
            *(*call).views.add(view)
        } else {
            // Unreachable if the host honoured the descriptor. A query that
            // yields nothing still beats one that reads a wild pointer.
            EMPTY_VIEW
        };
        Self {
            view,
            _p: PhantomData,
        }
    }

    pub fn iter(&self) -> QueryIter<'_, D, F> {
        QueryIter {
            view: self.view,
            row: 0,
            _p: PhantomData,
        }
    }

    pub fn iter_mut(&mut self) -> QueryIter<'_, D, F> {
        self.iter()
    }

    pub fn len(&self) -> usize {
        self.view.entity_count
    }

    pub fn is_empty(&self) -> bool {
        self.view.entity_count == 0
    }
}

/// Stands in when a view index is out of range. Empty, so iterating it is a
/// no-op rather than a fault.
const EMPTY_VIEW: sys::QueryView = sys::QueryView {
    cells: core::ptr::null_mut(),
    entities: core::ptr::null(),
    entity_count: 0,
    cell_count: 0,
};

pub struct QueryIter<'a, D: QueryData, F: QueryFilter> {
    view: sys::QueryView,
    row: usize,
    _p: PhantomData<(&'a (), D, F)>,
}

impl<'a, D: QueryData, F: QueryFilter> Iterator for QueryIter<'a, D, F> {
    type Item = D::Item<'a>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.row >= self.view.entity_count {
            return None;
        }
        // SAFETY: row < entity_count, and the host laid out `cell_count` cells
        // per row in declaration order.
        let item = unsafe {
            D::fetch(
                &self.view as *const sys::QueryView,
                self.row,
                self.view.cells.add(self.row * self.view.cell_count),
            )
        };
        self.row += 1;
        Some(item)
    }
}

impl<'a, D: QueryData, F: QueryFilter> IntoIterator for &'a Query<'_, D, F> {
    type Item = D::Item<'a>;
    type IntoIter = QueryIter<'a, D, F>;
    fn into_iter(self) -> Self::IntoIter {
        self.iter()
    }
}

impl<'a, D: QueryData, F: QueryFilter> IntoIterator for &'a mut Query<'_, D, F> {
    type Item = D::Item<'a>;
    type IntoIter = QueryIter<'a, D, F>;
    fn into_iter(self) -> Self::IntoIter {
        self.iter()
    }
}

// ── Resources ────────────────────────────────────────────────────────────────

/// A single global value, one per world. Mirrors `bevy::Resource`.
///
/// Emitted by `#[derive(Resource)]`. Registration and layout work exactly like a
/// component's, because in Bevy a resource *is* a component on a hidden entity —
/// the same descriptor, the same field schema, the same default constructor.
pub trait Resource: Sized + 'static {
    const TYPE_PATH: &'static str;
    fn display_name() -> &'static str;
    fn id_cell() -> &'static core::sync::atomic::AtomicU32;
    fn fields() -> &'static [sys::FieldDesc];
    fn descriptor() -> sys::ComponentDesc;
}

/// The id the host assigned `T`, or `INVALID` if it was never registered.
pub fn resource_id_of<T: Resource>() -> sys::ComponentId {
    sys::ComponentId(T::id_cell().load(core::sync::atomic::Ordering::Relaxed))
}

/// What can sit inside [`Res`] / [`ResMut`].
///
/// Two kinds satisfy this and they resolve differently, which is why it is its
/// own trait rather than folded into [`Resource`]: a plugin's own resource lives
/// in the host world and arrives as a pointer in
/// [`sys::SystemCall::resources`], while [`Time`] is read straight out of the
/// call's frame context and never round-trips through the world at all.
///
/// # Safety
/// `res_ptr` must return a pointer valid for the duration of the call, or null.
pub unsafe trait ResourceParam: Sized {
    fn res_term(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>, access: sys::Access);
    /// # Safety
    /// `call` must be live.
    unsafe fn res_ptr(call: *const sys::SystemCall) -> *mut Self;
}

unsafe impl<T: Resource> ResourceParam for T {
    fn res_term(ctx: &mut InitCtx, out: &mut alloc::vec::Vec<sys::Term>, access: sys::Access) {
        out.push(sys::Term { component: ctx.resource_id_of::<T>(), access });
    }
    unsafe fn res_ptr(call: *const sys::SystemCall) -> *mut T {
        let want = resource_id_of::<T>();
        let slots = core::slice::from_raw_parts((*call).resources, (*call).resource_count);
        slots
            .iter()
            .find(|s| s.id == want)
            .map_or(core::ptr::null_mut(), |s| s.ptr.cast())
    }
}

/// The frame clock. Mirrors `bevy::Time` for the parts a plugin can reach.
///
/// `#[repr(transparent)]` over the frame context so [`ResourceParam::res_ptr`]
/// can hand back a pointer to the live call's own field rather than to a
/// temporary — a `Res<Time>` borrows the call, exactly like every other param.
#[repr(transparent)]
pub struct Time(sys::FrameCtx);

impl Time {
    pub fn delta_secs(&self) -> f32 {
        self.0.delta_secs
    }
    pub fn elapsed_secs(&self) -> f32 {
        self.0.elapsed_secs
    }
}

unsafe impl ResourceParam for Time {
    // Declares nothing: the host sends the frame context with every call, so
    // there is no access to negotiate and no scheduling conflict to create.
    fn res_term(_: &mut InitCtx, _: &mut alloc::vec::Vec<sys::Term>, _: sys::Access) {}
    unsafe fn res_ptr(call: *const sys::SystemCall) -> *mut Time {
        core::ptr::addr_of!((*call).frame) as *mut Time
    }
}

/// Shared access to a resource. Mirrors `bevy::Res`.
pub struct Res<'a, T>(*mut T, PhantomData<&'a T>);

impl<T> Res<'_, T> {
    /// Whether the resource exists. Bevy would have skipped the whole system;
    /// here it runs and the plugin decides, which keeps a missing resource a
    /// local question rather than a silent scheduling puzzle.
    pub fn is_present(&self) -> bool {
        !self.0.is_null()
    }
    pub fn get(&self) -> Option<&T> {
        unsafe { self.0.as_ref() }
    }
}

impl<T> core::ops::Deref for Res<'_, T> {
    type Target = T;
    fn deref(&self) -> &T {
        self.get()
            .expect("resource not present — check `is_present()` first")
    }
}

/// Mutable access to a resource. Mirrors `bevy::ResMut`.
pub struct ResMut<'a, T>(*mut T, PhantomData<&'a mut T>);

impl<T> ResMut<'_, T> {
    pub fn is_present(&self) -> bool {
        !self.0.is_null()
    }
    pub fn get(&self) -> Option<&T> {
        unsafe { self.0.as_ref() }
    }
    pub fn get_mut(&mut self) -> Option<&mut T> {
        unsafe { self.0.as_mut() }
    }
}

impl<T> core::ops::Deref for ResMut<'_, T> {
    type Target = T;
    fn deref(&self) -> &T {
        self.get()
            .expect("resource not present — check `is_present()` first")
    }
}

impl<T> core::ops::DerefMut for ResMut<'_, T> {
    fn deref_mut(&mut self) -> &mut T {
        self.get_mut()
            .expect("resource not present — check `is_present()` first")
    }
}

// ── Commands ─────────────────────────────────────────────────────────────────

/// A group of components to insert together. Mirrors `bevy::Bundle`.
///
/// Implemented for any single component (emitted by `#[derive(Component)]`) and
/// for tuples of them, so `spawn((A, B, C))` reads exactly as it does in Bevy.
///
/// There is no blanket `impl<T: Component> Bundle for T` because it would
/// overlap with the tuple impls — Rust cannot prove a tuple is not a component.
/// The derive emitting it per-type sidesteps that.
pub trait Bundle {
    fn write(self, e: &mut EntityCommands);
}

/// A scene, ready to spawn. Produced by the [`bsn!`](crate::bsn) macro.
///
/// Named to match `bevy_scene::Scene`, and spawned the same way — through
/// [`Commands::spawn_scene`], not `spawn`. Bevy keeps them separate because a
/// scene is not a bundle: it describes a whole tree, and `spawn` takes the
/// components of one entity.
///
/// The source names components rather than carrying their bytes, which is why
/// one syntax reaches both the engine's components and the plugin's own: the
/// host resolves a name against the type registry first and the plugin schema
/// registry second, and the author never has to know which side a component is
/// on.
#[derive(Clone, Copy)]
pub struct Scene(pub &'static str);

impl Bundle for Scene {
    fn write(self, e: &mut EntityCommands) {
        if e.sink.is_null() {
            return;
        }
        let cmd = sys::Command {
            kind: sys::CommandKind::SpawnBsn,
            entity: e.id,
            component: sys::ComponentId::INVALID,
            data: self.0.as_ptr(),
            data_len: self.0.len(),
        };
        // SAFETY: the sink copies the bytes before returning, and the source is
        // `'static` regardless.
        unsafe { ((*e.sink).push)(e.sink, &cmd) };
    }
}

macro_rules! bundle_tuples {
    ($(($($p:ident),+))+) => {
        $(
            #[allow(non_snake_case)]
            impl<$($p: Bundle),+> Bundle for ($($p,)+) {
                fn write(self, e: &mut EntityCommands) {
                    let ($($p,)+) = self;
                    $($p.write(e);)+
                }
            }
        )+
    };
}

bundle_tuples! {
    (A)
    (A, B)
    (A, B, C)
    (A, B, C, D)
    (A, B, C, D, E)
    (A, B, C, D, E, F)
    (A, B, C, D, E, F, G)
    (A, B, C, D, E, F, G, H)
}

/// Queue structural changes. Mirrors `bevy::Commands`.
///
/// Deferred, like Bevy's: everything queued here is applied after the system
/// finishes. Spawning mid-iteration would invalidate the rows being walked.
pub struct Commands<'a> {
    sink: *mut sys::CommandSink,
    _p: PhantomData<&'a ()>,
}

impl<'a> Commands<'a> {
    /// Spawn an entity carrying `bundle`. Mirrors `bevy::Commands::spawn`.
    pub fn spawn<B: Bundle>(&mut self, bundle: B) -> EntityCommands<'_> {
        let mut e = self.spawn_empty();
        bundle.write(&mut e);
        e
    }

    /// Spawn a visible entity: mesh, material and transform in one go.
    ///
    /// Returns [`EntityCommands`] so plugin components can be attached to it in
    /// the same breath.
    pub fn spawn_mesh(
        &mut self,
        mesh: sys::AssetHandle,
        material: sys::AssetHandle,
        transform: Transform,
    ) -> EntityCommands<'_> {
        let mut e = self.spawn_empty();
        e.make_renderable(mesh, material, transform);
        e
    }

    /// Spawn a scene. Mirrors `bevy::Commands::spawn_scene`.
    ///
    /// ```ignore
    /// commands.spawn_scene(bsn! {
    ///     #Light
    ///     Transform { translation: Vec3(0.0, 6.0, 0.0) }
    ///     PointLight { intensity: 400000.0 }
    ///     Children [
    ///         Marker,
    ///     ]
    /// });
    /// ```
    ///
    /// The returned id is the scene's root. It is valid immediately, even though
    /// the tree materialises when commands are applied — the same reservation
    /// `spawn_empty` uses.
    pub fn spawn_scene(&mut self, scene: Scene) -> EntityCommands<'_> {
        self.spawn(scene)
    }

    /// Reserve an entity with nothing on it. The id is usable immediately — for
    /// parenting, for storing in a component — even though the entity itself
    /// appears when commands are applied.
    pub fn spawn_empty(&mut self) -> EntityCommands<'_> {
        let id = if self.sink.is_null() {
            sys::Entity(u64::MAX)
        } else {
            unsafe { ((*self.sink).reserve_entity)(self.sink) }
        };
        EntityCommands {
            id,
            sink: self.sink,
            _p: PhantomData,
        }
    }

    /// Queue changes for an existing entity.
    pub fn entity(&mut self, entity: sys::Entity) -> EntityCommands<'_> {
        EntityCommands {
            id: entity,
            sink: self.sink,
            _p: PhantomData,
        }
    }
}

/// Queued changes for one entity. Mirrors `bevy::EntityCommands`.
pub struct EntityCommands<'a> {
    id: sys::Entity,
    sink: *mut sys::CommandSink,
    /// Ties this to its `Commands`, so it cannot outlive the sink it writes to.
    _p: PhantomData<&'a ()>,
}

impl<'a> EntityCommands<'a> {
    pub fn id(&self) -> sys::Entity {
        self.id
    }

    /// Insert a bundle. Mirrors `bevy::EntityCommands::insert`.
    pub fn insert<B: Bundle>(&mut self, bundle: B) -> &mut Self {
        bundle.write(self);
        self
    }

    /// Queue one component, copying its bytes.
    ///
    /// Takes the value by move and forgets it: the host now owns those bytes and
    /// will run the component's destructor if it has one. Dropping here too
    /// would free twice.
    pub fn insert_one<T: Component>(&mut self, value: T) -> &mut Self {
        if self.sink.is_null() {
            return self;
        }
        let bytes = &value as *const T as *const u8;
        let cmd = sys::Command {
            kind: sys::CommandKind::Insert,
            entity: self.id,
            component: sys::ComponentId::INVALID,
            data: bytes,
            data_len: core::mem::size_of::<T>(),
        };
        // The host resolves the component from the descriptor rather than an id,
        // because a plugin has no way to know the id it was assigned without
        // asking — and asking mid-system is exactly what the sink exists to
        // avoid.
        let mut cmd = cmd;
        cmd.component = component_id_of::<T>();
        unsafe { ((*self.sink).push)(self.sink, &cmd) };
        core::mem::forget(value);
        self
    }

    /// Attach mesh, material and transform. Used by [`Commands::spawn_mesh`].
    pub fn make_renderable(
        &mut self,
        mesh: sys::AssetHandle,
        material: sys::AssetHandle,
        transform: Transform,
    ) -> &mut Self {
        if self.sink.is_null() {
            return self;
        }
        let desc = sys::SpawnMeshDesc {
            mesh,
            material,
            transform,
        };
        let cmd = sys::Command {
            kind: sys::CommandKind::SpawnMesh,
            entity: self.id,
            component: sys::ComponentId::INVALID,
            data: (&desc as *const sys::SpawnMeshDesc).cast(),
            data_len: core::mem::size_of::<sys::SpawnMeshDesc>(),
        };
        unsafe { ((*self.sink).push)(self.sink, &cmd) };
        self
    }

    pub fn remove<T: Component>(&mut self) -> &mut Self {
        if self.sink.is_null() {
            return self;
        }
        let cmd = sys::Command {
            kind: sys::CommandKind::Remove,
            entity: self.id,
            component: component_id_of::<T>(),
            data: core::ptr::null(),
            data_len: 0,
        };
        unsafe { ((*self.sink).push)(self.sink, &cmd) };
        self
    }

    /// Despawn this entity and its descendants.
    pub fn despawn(&mut self) {
        if self.sink.is_null() {
            return;
        }
        let cmd = sys::Command {
            kind: sys::CommandKind::Despawn,
            entity: self.id,
            component: sys::ComponentId::INVALID,
            data: core::ptr::null(),
            data_len: 0,
        };
        unsafe { ((*self.sink).push)(self.sink, &cmd) };
    }
}

// ── Systems ──────────────────────────────────────────────────────────────────

/// One argument a system can take. Mirrors `bevy::SystemParam`.
///
/// Systems used to be enumerated by parameter shape — `Query`, `Query + Time`,
/// `Query + Commands`, and so on — which needs a new impl for every combination
/// and explodes the moment a resource joins in. This is the same fix Bevy uses:
/// describe one parameter, derive every combination from tuples.
///
/// `fetch` takes a **raw pointer**, not a reference, and that is load-bearing
/// rather than sloppy. The obvious signature — `fn fetch<'a>(&'a SystemCall) ->
/// Self::Item<'a>` — makes the parameter type an associated type, and the
/// compiler cannot run an associated type backwards: given `fn spin(Query<..>,
/// Res<Time>)` it has no way to work out which `SystemParam` produced those
/// items, so every `add_systems` call fails with "type annotations needed".
/// Returning `Self` makes the parameter type *the* type in the signature, which
/// unifies directly. The lifetime inside `Self` is then unchecked, which is why
/// this trait is `unsafe`: the call outlives the system body, so borrowing from
/// it is sound, but nothing in the types enforces that.
///
/// # Safety
/// `terms` must declare every component `fetch` reads, or the host will build a
/// query that does not match what the system touches. `fetch` must not retain
/// anything past the call.
pub unsafe trait SystemParam: Sized {
    /// Declare what this parameter needs.
    ///
    /// A `Query` pushes its own term list as a **separate** query; everything
    /// else pushes resource terms, which are per-system rather than per-query. A
    /// single merged list was what limited a system to one query: two `Query`
    /// parameters had nowhere to be separate, so their terms AND-ed together and
    /// both read the same cells.
    fn declare(ctx: &mut InitCtx, out: &mut SystemBuilder);

    /// # Safety
    /// `call` must be live for at least as long as the returned value is used.
    /// `views` is the running index of query parameters seen so far, and must be
    /// advanced by exactly the number this parameter declared — the host returns
    /// one view per declared query, in declaration order, and the two walks have
    /// to stay in step.
    unsafe fn fetch(call: *const sys::SystemCall, views: &mut usize) -> Self;
}

/// Collects what a system's parameters declare, before it is registered.
#[derive(Default)]
pub struct SystemBuilder {
    pub(crate) queries: alloc::vec::Vec<alloc::vec::Vec<sys::Term>>,
    pub(crate) resources: alloc::vec::Vec<sys::Term>,
}

unsafe impl<D: QueryData, F: QueryFilter> SystemParam for Query<'_, D, F> {
    fn declare(ctx: &mut InitCtx, out: &mut SystemBuilder) {
        let mut terms = alloc::vec::Vec::new();
        D::terms(ctx, &mut terms);
        F::terms(ctx, &mut terms);
        out.queries.push(terms);
    }
    unsafe fn fetch(call: *const sys::SystemCall, views: &mut usize) -> Self {
        let index = *views;
        *views += 1;
        Query::new(call, index)
    }
}

unsafe impl<T: ResourceParam> SystemParam for Res<'_, T> {
    fn declare(ctx: &mut InitCtx, out: &mut SystemBuilder) {
        T::res_term(ctx, &mut out.resources, sys::Access::ResRead);
    }
    unsafe fn fetch(call: *const sys::SystemCall, _: &mut usize) -> Self {
        Res(T::res_ptr(call), PhantomData)
    }
}

unsafe impl<T: ResourceParam> SystemParam for ResMut<'_, T> {
    fn declare(ctx: &mut InitCtx, out: &mut SystemBuilder) {
        T::res_term(ctx, &mut out.resources, sys::Access::ResWrite);
    }
    unsafe fn fetch(call: *const sys::SystemCall, _: &mut usize) -> Self {
        ResMut(T::res_ptr(call), PhantomData)
    }
}

unsafe impl SystemParam for Commands<'_> {
    fn declare(_: &mut InitCtx, _: &mut SystemBuilder) {}
    unsafe fn fetch(call: *const sys::SystemCall, _: &mut usize) -> Self {
        Commands {
            sink: (*call).commands,
            _p: PhantomData,
        }
    }
}

macro_rules! param_tuples {
    ($(($($p:ident),+))+) => {
        $(
            unsafe impl<$($p: SystemParam),+> SystemParam for ($($p,)+) {
                fn declare(ctx: &mut InitCtx, out: &mut SystemBuilder) {
                    $($p::declare(ctx, out);)+
                }
                unsafe fn fetch(call: *const sys::SystemCall, views: &mut usize) -> Self {
                    // Declaration order and fetch order are the same walk over
                    // the same tuple, which is what keeps view indices aligned.
                    ($($p::fetch(call, views),)+)
                }
            }
        )+
    };
}

param_tuples! {
    (A)
    (A, B)
    (A, B, C)
    (A, B, C, D)
    (A, B, C, D, E)
    (A, B, C, D, E, F)
}

/// A function that can be registered as a system.
///
/// Implemented for the *callable* rather than for `fn(..)` pointer types, which
/// matters for ergonomics: a bare `spin` is a fn **item**, a distinct
/// zero-sized type that only coerces to a pointer at a coercion site. Impl'ing
/// on the pointer would force every call to read `add_systems(Update, spin as
/// fn(_, _))`, and "identical to Bevy source" is the whole point.
///
/// The callable must be zero-sized — fn items and non-capturing closures
/// qualify, capturing closures do not. Enforced at compile time in
/// [`materialize`]; a capturing closure would need storage the host has no way
/// to own, so rejecting it is correct rather than a limitation to lift later.
pub trait IntoSystem<Marker> {
    fn build(self, ctx: &mut InitCtx) -> (SystemBuilder, sys::SystemEntry, *mut core::ffi::c_void);
}

/// Reconstruct a zero-sized callable from nothing.
///
/// Sound because a ZST has exactly one value and no bytes to be wrong about; the
/// const assertion is what keeps it that way if someone passes a capturing
/// closure.
#[inline(always)]
unsafe fn materialize<T>() -> T {
    const {
        assert!(
            core::mem::size_of::<T>() == 0,
            "a system must be a plain fn or a non-capturing closure — a capturing              closure has state the host cannot own",
        );
    }
    // Reading a zero-sized value through a dangling-but-aligned, non-null
    // pointer is the sanctioned way to materialise a ZST — it touches no memory,
    // because there is none to touch. `MaybeUninit::assume_init` would express
    // the same thing but is deny-by-default under clippy, which cannot see the
    // const assertion above that makes it sound.
    core::ptr::NonNull::<T>::dangling().as_ptr().read()
}

/// Marker distinguishing one parameter-tuple impl from another, so they don't
/// overlap.
pub struct ParamsMarker<P>(PhantomData<P>);

/// Run a system body, converting a panic into a status the host can act on.
///
/// A panic unwinding out of an `extern "C"` function aborts the process, so
/// without this one bad index in a half-written system takes the editor down.
/// `AssertUnwindSafe` is required because the call carries raw pointers; that is
/// sound here because a panic leaves host memory in whatever state the partial
/// loop wrote — data the host owns and re-reads next frame, with no plugin-side
/// invariants to break.
unsafe fn guard(call: &sys::SystemCall, body: impl FnOnce()) -> sys::SystemStatus {
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(body)) {
        Ok(()) => sys::SystemStatus::Ok,
        Err(e) => {
            let msg = e
                .downcast_ref::<&str>()
                .map(alloc::string::ToString::to_string)
                .or_else(|| e.downcast_ref::<alloc::string::String>().cloned())
                .unwrap_or_else(|| alloc::string::String::from("panic"));
            if !call.iface.is_null() {
                ((*call.iface).log)(
                    call.host,
                    sys::LogLevel::Error,
                    sys::StrRef {
                        ptr: msg.as_ptr(),
                        len: msg.len(),
                    },
                );
            }
            sys::SystemStatus::Panicked
        }
    }
}

/// One `IntoSystem` impl per arity. The thunk lives inside the expansion because
/// calling the function needs the parameters spread, not tupled — there is no
/// variadic form to write it once.
///
/// The bound is `Fn($($p),+)` over the *parameter* types rather than over fetched
/// item types, so inference runs the right way: the compiler matches `spin`'s
/// signature against it and reads `P = Query<..>, Res<Time>` straight off, then
/// looks up each one's `SystemParam` impl.
macro_rules! into_system {
    ($(($($p:ident),+))+) => {
        $(
            impl<$($p,)+ Func> IntoSystem<ParamsMarker<($($p,)+)>> for Func
            where
                $($p: SystemParam,)+
                Func: Fn($($p),+) + 'static,
            {
                fn build(
                    self,
                    ctx: &mut InitCtx,
                ) -> (SystemBuilder, sys::SystemEntry, *mut core::ffi::c_void) {
                    unsafe extern "C" fn thunk<$($p,)+ Fun>(
                        call: *const sys::SystemCall,
                    ) -> sys::SystemStatus
                    where
                        $($p: SystemParam,)+
                        Fun: Fn($($p),+) + 'static,
                    {
                        // Rust does not order argument evaluation across a call,
                        // so the view counter is advanced in a `let` chain first
                        // and the results handed over already fetched. Left to
                        // the call site, two `Query` params could take each
                        // other's view.
                        let mut views = 0usize;
                        $(#[allow(non_snake_case)] let $p = $p::fetch(call, &mut views);)+
                        guard(&*call, move || materialize::<Fun>()($($p),+))
                    }

                    let mut builder = SystemBuilder::default();
                    $($p::declare(ctx, &mut builder);)+
                    (builder, thunk::<$($p,)+ Func>, core::ptr::null_mut())
                }
            }
        )+
    };
}

into_system! {
    (A)
    (A, B)
    (A, B, C)
    (A, B, C, D)
    (A, B, C, D, E)
    (A, B, C, D, E, F)
}

